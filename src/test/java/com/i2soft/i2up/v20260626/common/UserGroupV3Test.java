@FixMethodOrder(MethodSorters.NAME_ASCENDING)
public class UserGroupV3Test {

    private static Auth auth;
    private static UserGroupV3 userGroupV3;

    @BeforeClass
    public static void setUp() {
        if (userGroupV3 != null) {
            return;
        }
        try {
            auth = Auth.token(TestConfig.addr, TestConfig.user, TestConfig.pwd, TestConfig.cachePath, new Configuration());
        } catch (I2softException e) {
            e.printStackTrace();
        }
        userGroupV3 = new UserGroupV3(auth);
    }

    @Test
    public void T9891_modifyUserGroupResBind() {
        try {
            Response r = auth.client.get(String.format(TestConfig.rapDataUrl, "9891")); // 获取请求数据
            StringMap args = new StringMap().putAll(Objects.requireNonNull(r.jsonToMap())); // 填充请求数据
            I2Rs.I2SmpRs rs = userGroupV3.modifyUserGroupResBind(args); // 发送请求
            Assert.assertNotNull(rs); // 检查结果
        } catch (I2softException e) {
            e.printStackTrace();
        }
    }

    @Test
    public void T9892_listUserGroupResBind() {
        try {
            Response r = auth.client.get(String.format(TestConfig.rapDataUrl, "9892")); // 获取请求数据
            StringMap args = new StringMap().putAll(Objects.requireNonNull(r.jsonToMap())); // 填充请求数据
            Map rs = userGroupV3.listUserGroupResBind(args); // 发送请求
            Assert.assertNotNull(rs); // 检查结果
        } catch (I2softException e) {
            e.printStackTrace();
        }
    }
}